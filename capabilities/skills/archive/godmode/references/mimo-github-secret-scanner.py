CODE_EXTENSIONS = {'.py','.js','.ts','.env','.json','.yaml','.yml','.toml','.sh','.md','.txt','.tf','.cfg'}
IGNORE_PATTERNS = {'node_modules','.git','vendor','venv','__pycache__','dist','build'}

PLACEHOLDER_INDICATORS = ['example','placeholder','your_key','your-api','insert_','replace_',
    'xxx','yyy','dummy','fake','test_','sample','<your','${','{{','changeme','todo']

class GitHubScanner:
    BASE_URL = "https://api.github.com"

    def __init__(self, token, org=None):
        self.session = requests.Session()
        self.session.headers.update({
            "Authorization": f"token {token}",
            "Accept": "application/vnd.github.v3+json",
            "X-GitHub-Api-Version": "2022-11-28",
        })
        self.org = org
        self.results = []

    def _request(self, method, url, **kwargs):
        for attempt in range(3):
            resp = self.session.request(method, url, **kwargs)
            if resp.status_code == 403 and resp.headers.get("X-RateLimit-Remaining") == "0":
                reset = int(resp.headers.get("X-RateLimit-Reset", 0))
                wait = max(reset - int(time.time()), 0) + 5
                print(f"[!] Rate limit. Waiting {wait}s...")
                time.sleep(wait)
                continue
            if resp.status_code == 429:
                time.sleep(int(resp.headers.get("Retry-After", 60)))
                continue
            return resp
        return resp

    def search_code(self, query, repo=None):
        results = []
        search_query = query
        if repo:
            search_query += f" repo:{repo}"
        elif self.org:
            search_query += f" org:{self.org}"

        for page in range(1, 6):  # Max 5 pages
            resp = self._request("GET", f"{self.BASE_URL}/search/code", params={
                "q": search_query, "per_page": 100, "page": page
            })
            if resp.status_code != 200:
                break
            items = resp.json().get("items", [])
            if not items:
                break
            results.extend(items)
            time.sleep(2)
        return results

    def get_file_content(self, repo, path):
        url = f"{self.BASE_URL}/repos/{repo}/contents/{quote(path, safe='/')}"
        resp = self._request("GET", url)
        if resp.status_code != 200:
            resp = self._request("GET", url, params={"ref": "master"})
            if resp.status_code != 200:
                return None
        data = resp.json()
        content = data.get("content", "")
        if data.get("encoding") == "base64":
            try:
                return base64.b64decode(content).decode("utf-8", errors="replace")
            except:
                return None
        return content

    def _is_placeholder(self, key, content, position):
        start = max(0, position - 50)
        end = min(len(content), position + len(key) + 50)
        context = content[start:end].lower()
        for ind in PLACEHOLDER_INDICATORS:
            if ind in context:
                return True
        if len(key) < 20 or len(set(key)) < 10:
            return True
        return False

    def extract_secrets(self, content, filename):
        findings = []
        for key_type, config in SECRET_PATTERNS.items():
            for match in re.finditer(config["pattern"], content):
                key = match.group(0)
                if self._is_placeholder(key, content, match.start()):
                    continue
                masked = key[:8] + "*" * (len(key) - 12) + key[-4:] if len(key) > 12 else key[:4] + "***"
                findings.append({
                    "key_type": key_type,
                    "provider": config["provider"],
                    "key_preview": masked,
                    "key_full": key,
                    "key_length": len(key),
                    "file": filename,
                    "line": content[:match.start()].count('\n') + 1,
                })
        return findings

    def scan_repo(self, repo, verbose=False):
        findings = []
        for key_type, config in SECRET_PATTERNS.items():
            if verbose:
                print(f"  [{repo}] Searching {config['provider']}...")
            query = f'"{config["prefix"]}" extension:env OR extension:json OR extension:yaml OR extension:py OR extension:js'
            try:
                results = self.search_code(query, repo=repo)
            except Exception as e:
                print(f"  [!] Error: {e}")
                continue
            for item in results:
                filename = item.get("path", "")
                if any(ign in filename for ign in IGNORE_PATTERNS):
                    continue
                ext = Path(filename).suffix.lower()
                if ext and ext not in CODE_EXTENSIONS:
                    continue
                content = self.get_file_content(repo, filename)
                if not content:
                    continue
                secrets = self.extract_secrets(content, filename)
                for s in secrets:
                    if s["key_type"] == key_type:
                        s["repo"] = repo
                        s["file_url"] = f"https://github.com/{repo}/blob/main/{filename}"
                        s["detected_at"] = datetime.utcnow().isoformat()
                        findings.append(s)
            time.sleep(1)
        return findings

    def scan_all(self, repos=None, verbose=False):
        all_findings = []
        for i, repo in enumerate(repos or [], 1):
            print(f"[{i}/{len(repos)}] Scanning {repo}")
            findings = self.scan_repo(repo, verbose)
            all_findings.extend(findings)
            if findings:
                print(f"  -> {len(findings)} secret(s) found!")
        return all_findings


def validate_key(provider_config, key_full):
    url = provider_config["validate_url"].format(key=key_full)
    headers = {}
    if provider_config.get("validate_header"):
        headers[provider_config["validate_header"]] = provider_config["validate_header_value"].format(key=key_full)
    try:
        resp = requests.get(url, headers=headers, timeout=10)
        if resp.status_code in (200, 401, 403):
            return resp.status_code == 200
    except:
        pass
    return False


def main():
    parser = argparse.ArgumentParser(description="GitHub Secret Scanner")
    parser.add_argument("--token", required=True, help="GitHub PAT")
    parser.add_argument("--org", required=True, help="GitHub org to scan")
    parser.add_argument("--output", default="secrets_report.json", help="Output JSON file")
    parser.add_argument("--repos", nargs="*", help="Specific repos to scan (default: all)")
    parser.add_argument("--verbose", action="store_true")
    parser.add_argument("--validate", action="store_true", help="Validate found keys against provider APIs")
    args = parser.parse_args()

    scanner = GitHubScanner(args.token, args.org)

    if args.repos:
        repos = args.repos
    else:
        print(f"[*] Getting repos for {args.org}...")
        resp = scanner._request("GET", f"{scanner.BASE_URL}/orgs/{args.org}/repos",
            params={"type": "public", "per_page": 100})
        repos = [r["full_name"] for r in resp.json()] if resp.status_code == 200 else []

    print(f"[*] {len(repos)} repos to scan\n")
    findings = scanner.scan_all(repos, args.verbose)

    if args.validate and findings:
        print(f"\n[*] Validating {len(findings)} found keys...")
        for f in findings:
            config = SECRET_PATTERNS.get(f["key_type"], {})
            if config.get("validate_url"):
                active = validate_key(config, f["key_full"])
                f["status"] = "ACTIVE" if active else "INACTIVE/EXPIRED"
                print(f"  [{f['provider']}] {f['key_preview']} -> {f['status']}")
            else:
                f["status"] = "NO_VALIDATE_ENDPOINT"
            del f["key_full"]  # Remove full key from report
    else:
        for f in findings:
            f["status"] = "FOUND - Not validated"
            if "key_full" in f:
                del f["key_full"]

    report = {
        "scan_metadata": {
            "tool": "github-secret-scanner",
            "timestamp": datetime.utcnow().isoformat(),
            "org": args.org,
            "repos_scanned": len(repos),
            "total_findings": len(findings),
            "by_provider": {},
        },
        "findings": findings,
    }
    for f in findings:
        p = f["provider"]
        report["scan_metadata"]["by_provider"][p] = report["scan_metadata"]["by_provider"].get(p, 0) + 1

    with open(args.output, 'w') as fp:
        json.dump(report, fp, indent=2, ensure_ascii=False)

    print(f"\n{'='*60}")
    print(f" SCAN COMPLETE: {len(findings)} secrets found")
    print(f" Report saved to: {args.output}")
    print(f"{'='*60}")
    for f in findings:
        print(f"  [{f['provider']}] {f['key_preview']} in {f['repo']}/{f['file']} ({f['status']})")


if __name__ == "__main__":
    main()
