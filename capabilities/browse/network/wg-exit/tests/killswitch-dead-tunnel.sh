#!/bin/sh
# Kill switch of a scoped exit with a DEAD tunnel (no account needed): the same image, flags and rules as
# walter-wg-exit, a random private key against a real NordLynx server of the country -> no handshake. Expected: the
# proxy answers nothing, no request or DNS query leaves the container except the tunnel's own UDP, and removing the
# tunnel interface does not open the bridge route. Exit 0 = no leak. Usage: killswitch-dead-tunnel.sh [country_id]
set -u
CID=${1:-108}; C=walter-wg-killswitch-test; PORT=21999; IMG=walter-wg-exit:latest
S=$(curl -s -m 20 "https://api.nordvpn.com/v1/servers/recommendations?filters\[country_id\]=$CID&filters\[servers_technologies\]\[identifier\]=wireguard_udp&limit=1")
PUB=$(echo "$S" | python3 -c 'import json,sys; s=json.load(sys.stdin)[0]; t=[t for t in s["technologies"] if t["identifier"]=="wireguard_udp"][0]; print([m["value"] for m in t["metadata"] if m["name"]=="public_key"][0])')
EP=$(echo "$S" | python3 -c 'import json,sys; print(json.load(sys.stdin)[0]["station"])')
KEY=$(docker run --rm --entrypoint wg $IMG genkey)
RUN=$(mktemp -d /dev/shm/walter-wg-test-XXXX); chmod 700 "$RUN"
printf '[Interface]\nPrivateKey = %s\nAddress = 10.5.0.2/32\nDNS = 103.86.96.100\n\n[Peer]\nPublicKey = %s\nAllowedIPs = 0.0.0.0/0\nEndpoint = %s:51820\n' "$KEY" "$PUB" "$EP" > "$RUN/wg0.conf"; KEY=
docker rm -f $C >/dev/null 2>&1
docker run -d --name $C --restart no --cap-add NET_ADMIN --sysctl net.ipv4.conf.all.src_valid_mark=1 \
  --sysctl net.ipv6.conf.all.disable_ipv6=1 -p 127.0.0.1:$PORT:8888 -v "$RUN:/run/wg:ro" $IMG >/dev/null
for i in $(seq 1 20); do docker exec $C pgrep tinyproxy >/dev/null 2>&1 && break; sleep 1; done
rm -rf "$RUN"
fail=0
check() { if [ "${2:-}" = leak ]; then echo "LEAK  $1"; fail=1; else echo "ok    $1"; fi; }
# a remote answer through the proxy (anything but tinyproxy's own "unable to connect" page or no answer at all)
remote() { b=$(curl -s -m 12 -x http://127.0.0.1:$PORT "$1"); [ -n "$b" ] && ! printf '%s' "$b" | grep -q 'Generated by tinyproxy'; }
out=$(curl -s -m 12 -x http://127.0.0.1:$PORT https://api.ipify.org); [ -n "$out" ] && check "proxy request answered ($out)" leak || check "proxy request gets nothing (dead tunnel)"
remote http://neverssl.com && check "plain http answered by a remote server" leak || check "plain http: only the proxy's own error page"
docker exec $C sh -c 'nslookup -timeout=4 example.com 8.8.8.8 >/dev/null 2>&1' && check "DNS to 8.8.8.8 from the container" leak || check "DNS outside the tunnel blocked"
docker exec $C sh -c 'wget -T 5 -qO- http://1.1.1.1 >/dev/null 2>&1' && check "direct TCP from the container" leak || check "direct TCP outside the tunnel blocked"
docker exec $C ip link del wg0 2>/dev/null
out=$(curl -s -m 12 -x http://127.0.0.1:$PORT https://api.ipify.org); [ -n "$out" ] && check "tunnel interface removed: proxy answered ($out)" leak || check "tunnel interface removed: still nothing (bridge route closed)"
docker exec $C sh -c 'wget -T 5 -qO- http://1.1.1.1 >/dev/null 2>&1' && check "tunnel removed: direct TCP" leak || check "tunnel removed: direct TCP blocked"
docker rm -f $C >/dev/null
exit $fail
